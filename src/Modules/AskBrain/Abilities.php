<?php

declare(strict_types=1);

namespace AgentBrain\Modules\AskBrain;

use AgentBrain\Modules\Artifacts\Cpts;
use AgentBrain\Modules\Artifacts\ObjectAccess;
use AgentBrain\Modules\Identity\Scopes;
use AgentBrain\Modules\Mcp\AbilityNames;
use AgentBrain\Modules\Mcp\Module as McpModule;
use AgentBrain\Modules\Sharing\ShareAbilities;
use WP_Error;

/**
 * ART-26 (#166): the agent-brain/ask MCP ability — the same question engine
 * (Asker) as the page endpoint, for authenticated brain members. A caller
 * may ask about an artifact whose scope they may read (or which they
 * curate); the same per-artifact + site daily cost caps apply and every
 * call is audited with the caller as the actor. Read-only: not
 * WriteLimiter-gated, but provider-budget bounded.
 */
final class Abilities {

	public static function register(): void {
		if ( ! function_exists( 'wp_register_ability' ) ) {
			return;
		}

		ShareAbilities::registerOnce(
			AbilityNames::ASK,
			[
				'label'               => __( 'Ask the brain', 'agent-brain' ),
				'description'         => __( 'Ask a question about an artifact and receive an answer drawn from its scope, generated by the site\'s configured AI provider with citations to the memories and approved knowledge used. The caller must be able to read the artifact\'s scope (or curate it); the answer can only draw on that scope. Per-artifact and site daily cost caps apply and every call is audited.', 'agent-brain' ),
				'category'            => McpModule::CATEGORY,
				'input_schema'        => [
					'type'       => 'object',
					'properties' => [
						'artifact_id' => [ 'type' => 'integer', 'minimum' => 1 ],
						'question'    => [ 'type' => 'string', 'minLength' => 1, 'maxLength' => Asker::QUESTION_MAX ],
					],
					'required'   => [ 'artifact_id', 'question' ],
				],
				'output_schema'       => [
					'type'       => 'object',
					'properties' => [
						'answer'    => [ 'type' => 'object' ],
						'citations' => [ 'type' => 'array', 'items' => [ 'type' => 'object' ] ],
						'usage'     => [ 'type' => 'object' ],
					],
					'required'   => [ 'answer', 'citations', 'usage' ],
				],
				'permission_callback' => static fn ( $input ): bool => self::can( $input ),
				'execute_callback'    => static function ( $input ) {
					$input      = is_array( $input ) ? $input : [];
					$artifactId = (int) ( $input['artifact_id'] ?? 0 );
					$question   = isset( $input['question'] ) && is_string( $input['question'] ) ? $input['question'] : '';

					return self::run( $artifactId, $question );
				},
			]
		);
	}

	/**
	 * @param mixed $input
	 */
	private static function can( $input ): bool {
		$actorId = ShareAbilities::actorId();
		if ( ! ShareAbilities::canUseMcp() ) {
			return false;
		}

		$artifactId = is_array( $input ) ? (int) ( $input['artifact_id'] ?? 0 ) : 0;
		if ( $artifactId <= 0 ) {
			// Discovery fallback (no concrete object to evaluate against):
			// anyone who curates or holds any read scope may see the tool.
			return ObjectAccess::userIsCurator( $actorId ) || ( new Scopes() )->readScopeIds( $actorId ) !== [];
		}

		return self::canReadArtifactScope( $actorId, $artifactId );
	}

	private static function canReadArtifactScope( int $actorId, int $artifactId ): bool {
		$post = get_post( $artifactId );
		if ( ! $post instanceof \WP_Post || $post->post_type !== Cpts::ARTIFACT_POST_TYPE ) {
			return false;
		}

		$scopeId = (int) get_post_meta( $artifactId, Cpts::META_SCOPE_ID, true );

		return $scopeId > 0 && ( ObjectAccess::userIsCurator( $actorId ) || ( new Scopes() )->canRead( $actorId, $scopeId ) );
	}

	/**
	 * @return array<string, mixed>|WP_Error
	 */
	private static function run( int $artifactId, string $question ) {
		$actorId = ShareAbilities::actorId();
		if ( ! self::canReadArtifactScope( $actorId, $artifactId ) ) {
			return new WP_Error( 'ab_forbidden', __( 'You do not have permission to ask about this artifact.', 'agent-brain' ), [ 'status' => 403 ] );
		}

		$scopeId = (int) get_post_meta( $artifactId, Cpts::META_SCOPE_ID, true );

		$result = ( new Asker( Selector::select() ) )->ask( $question, [ $scopeId ], $artifactId );
		if ( $result instanceof WP_Error ) {
			self::audit( $actorId, $artifactId, 'error', [ 'error' => $result->get_error_code() ] );

			return $result;
		}

		$usage = $result['usage'];
		self::audit(
			$actorId,
			$artifactId,
			'ok',
			[
				'question'          => mb_substr( trim( $question ), 0, 120 ),
				'citations'         => array_map(
					static fn ( array $item ): array => [ 'kind' => (string) ( $item['kind'] ?? '' ), 'id' => (int) ( $item['id'] ?? 0 ) ],
					$result['citations']
				),
				'provider'          => (string) ( $usage['provider'] ?? '' ),
				'prompt_tokens'     => (int) ( $usage['prompt_tokens'] ?? 0 ),
				'completion_tokens' => (int) ( $usage['completion_tokens'] ?? 0 ),
			]
		);

		return $result;
	}

	/**
	 * Audited against the artifact itself (no share link exists on this
	 * path): object_type artifact, object_id the artifact id.
	 *
	 * @param array<string, mixed> $meta
	 */
	private static function audit( int $actorId, int $artifactId, string $status, array $meta ): void {
		do_action(
			'agent_brain/audit',
			[
				'actor_id'    => $actorId,
				'event'       => 'ask_brain_question',
				'status'      => $status,
				'object_type' => 'artifact',
				'object_id'   => (string) $artifactId,
				'meta'        => $meta,
			]
		);
	}
}
