<?php

declare(strict_types=1);

namespace AgentBrain\Modules\AskBrain;

use AgentBrain\Modules\Artifacts\Cpts;
use AgentBrain\Modules\Sharing\ArtifactSettings;
use AgentBrain\Modules\Sharing\ViewerMode;

/**
 * Curator-only "Ask the brain" box on the artifact edit screen (ART-26,
 * #166) — the BrainRead\MetaBox pattern, plus the per-artifact daily cost
 * cap field (Spend) in the same box so the budget is set where the switch
 * is flipped.
 */
final class MetaBox {

	public const NONCE_ACTION = 'ab_ask_brain_toggle';
	public const NONCE_FIELD  = 'ab_ask_brain_nonce';
	public const FIELD        = 'ab_ask_brain';
	public const FIELD_CAP    = 'ab_ask_brain_cap';

	public static function register(): void {
		add_action( 'init', [ self::class, 'registerMeta' ] );
		add_action( 'add_meta_boxes_' . Cpts::ARTIFACT_POST_TYPE, [ self::class, 'addMetaBox' ] );
		add_action( 'save_post_' . Cpts::ARTIFACT_POST_TYPE, [ self::class, 'save' ], 10, 1 );
	}

	/**
	 * The flag and the cap must not be writable through the generic meta
	 * APIs / Custom Fields box by non-curators.
	 */
	public static function registerMeta(): void {
		register_post_meta(
			Cpts::ARTIFACT_POST_TYPE,
			Mode::META_FLAG,
			[
				'type'          => 'string',
				'single'        => true,
				'show_in_rest'  => false,
				'auth_callback' => static fn ( $allowed, $metaKey, $objectId, $userId ): bool => Mode::canToggle( (int) $userId ),
			]
		);

		register_post_meta(
			Cpts::ARTIFACT_POST_TYPE,
			Mode::META_CAP,
			[
				'type'          => 'number',
				'single'        => true,
				'show_in_rest'  => false,
				'auth_callback' => static fn ( $allowed, $metaKey, $objectId, $userId ): bool => Mode::canToggle( (int) $userId ),
			]
		);
	}

	public static function addMetaBox( \WP_Post $post ): void {
		unset( $post );
		if ( ! Mode::canToggle( get_current_user_id() ) ) {
			return;
		}

		add_meta_box( 'ab_artifact_ask_brain', __( 'Ask the brain', 'tomatio' ), [ self::class, 'render' ], Cpts::ARTIFACT_POST_TYPE, 'side', 'low' );
	}

	public static function render( \WP_Post $post ): void {
		echo self::html( (int) $post->ID ); // phpcs:ignore WordPress.Security.EscapeOutput -- built with esc_* in html().
	}

	public static function html( int $artifactId ): string {
		$cap = get_post_meta( $artifactId, Mode::META_CAP, true );

		$out  = wp_nonce_field( self::NONCE_ACTION, self::NONCE_FIELD, true, false );
		$out .= '<p><label><input type="checkbox" name="' . esc_attr( self::FIELD ) . '" value="1"' . checked( Mode::isFlagged( $artifactId ), true, false ) . ' /> ';
		$out .= esc_html( ArtifactSettings::label( ArtifactSettings::ASK_BRAIN ) ) . '</label></p>';
		$out .= '<p><label for="' . esc_attr( self::FIELD_CAP ) . '">' . esc_html( ArtifactSettings::label( ArtifactSettings::ASK_DAILY_BUDGET_USD ) ) . '</label> ';
		$out .= '<input type="number" name="' . esc_attr( self::FIELD_CAP ) . '" id="' . esc_attr( self::FIELD_CAP ) . '" value="' . esc_attr( is_numeric( $cap ) ? (string) $cap : '' ) . '" step="0.01" min="0" class="small-text" /></p>';
		$out .= '<p class="description">' . esc_html__( 'Pages can ask a question and receive an answer with citations to the memories and approved knowledge of the artifact\'s scope, generated by the site\'s configured AI provider. Named viewers only get what their read grants allow; everyone else the scope read-only. Every call is rate limited, cost-capped and audited. Requires viewer identity. Off by default.', 'tomatio' ) . '</p>';
		if ( Mode::killSwitchOn() ) {
			$out .= '<p class="description"><strong>' . esc_html__( 'Ask the brain is disabled site-wide.', 'tomatio' ) . '</strong></p>';
		} elseif ( ! ViewerMode::isActive( $artifactId ) ) {
			$out .= '<p class="description"><strong>' . esc_html__( 'Requires viewer identity to be enabled for this artifact.', 'tomatio' ) . '</strong></p>';
		}

		return $out;
	}

	public static function save( int $postId ): void {
		if ( defined( 'DOING_AUTOSAVE' ) && DOING_AUTOSAVE ) {
			return;
		}

		$nonce = isset( $_POST[ self::NONCE_FIELD ] ) ? sanitize_text_field( wp_unslash( (string) $_POST[ self::NONCE_FIELD ] ) ) : '';
		if ( $nonce === '' || ! wp_verify_nonce( $nonce, self::NONCE_ACTION ) ) {
			return;
		}

		$on = isset( $_POST[ self::FIELD ] ) && (string) wp_unslash( $_POST[ self::FIELD ] ) === '1'; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- compared to a literal.
		Mode::set( $postId, $on, get_current_user_id() );

		$rawCap = isset( $_POST[ self::FIELD_CAP ] ) ? sanitize_text_field( wp_unslash( (string) $_POST[ self::FIELD_CAP ] ) ) : '';
		Mode::setCap( $postId, $rawCap === '' ? null : (float) $rawCap, get_current_user_id() );
	}
}
